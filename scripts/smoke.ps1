param(
  [string]$BaseUrl = 'http://localhost',
  [switch]$SkipDocker
)
$ErrorActionPreference = 'Stop'
if (-not $SkipDocker) {
  docker compose config --quiet
  if ($LASTEXITCODE -ne 0) { throw 'Docker Compose configuration invalid' }
  docker compose up -d --build
  if ($LASTEXITCODE -ne 0) { throw 'Docker Compose start failed' }
  docker compose ps
}
function Wait-Url([string]$url, [string]$expectedText) {
  for ($i = 0; $i -lt 45; $i++) {
    try {
      $response = Invoke-WebRequest -Uri $url -UseBasicParsing -TimeoutSec 4
      if ($response.StatusCode -eq 200 -and $response.Content.Contains($expectedText)) {
        Write-Host "PASS $url" -ForegroundColor Green
        return
      }
    } catch {}
    Start-Sleep -Seconds 3
  }
  throw "FAIL $url (expected 200 and text '$expectedText')"
}
Wait-Url "$BaseUrl/" 'Generated by forger'
Wait-Url 'http://127.0.0.1/' 'Generated by forger'
Wait-Url "$BaseUrl/api/hello" 'Hello from forger'
Wait-Url "$BaseUrl/api/actuator/health" '"status":"UP"'
Write-Host 'PASS all HTTP smoke tests' -ForegroundColor Green
